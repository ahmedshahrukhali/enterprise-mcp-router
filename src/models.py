"""
Pydantic v2 Schemas & Data Contracts for Enterprise-MCP-Router.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class MCPJsonRpcRequest(BaseModel):
    jsonrpc: str = Field(default="2.0", description="JSON-RPC protocol version")
    id: Optional[Any] = Field(default=1, description="Request correlation ID")
    method: str = Field(..., description="MCP method (e.g., initialize, tools/list, tools/call, resources/list)")
    params: Dict[str, Any] = Field(default_factory=dict, description="Method parameters")


class MCPJsonRpcResponse(BaseModel):
    jsonrpc: str = "2.0"
    id: Optional[Any] = 1
    result: Optional[Dict[str, Any]] = None
    error: Optional[Dict[str, Any]] = None


class SemanticRouteRequest(BaseModel):
    query: str = Field(
        default="Query Snowflake Cortex Search for RRSP compliance guidelines and fund NAV",
        description="Natural language agent intent or user query",
    )
    top_k: int = Field(default=5, ge=1, le=25, description="Number of top semantic tools to route")
    domain_filter: Optional[str] = Field(default=None, description="Optional enterprise namespace filter")


class RoutedToolItem(BaseModel):
    name: str
    domain: str
    description: str
    is_mutating: bool
    required_role: str
    similarity_score: float
    schema_tokens: int


class SemanticRouteResponse(BaseModel):
    query: str
    top_k: int
    total_registered_tools: int
    full_registry_tokens: int
    routed_tokens: int
    token_reduction_pct: float
    routing_latency_ms: float
    routed_tools: List[RoutedToolItem]


class AuthorizationRequest(BaseModel):
    tool_name: str = Field(..., description="Target MCP tool name")
    user_roles: List[str] = Field(default_factory=lambda: ["analyst"], description="OAuth2 / RBAC roles")
    hitl_approved: bool = Field(default=False, description="Whether HITL approval token is present")
    hitl_ticket_id: Optional[str] = Field(default=None, description="Optional approved HITL ticket ID")
    arguments: Dict[str, Any] = Field(default_factory=dict, description="Tool invocation arguments")


class HITLCreateRequest(BaseModel):
    tool_name: str = Field(..., description="Mutating tool requiring human approval")
    requested_by: str = Field(default="agent_workflow_prod_01", description="Agent or user principal")
    user_roles: List[str] = Field(default_factory=lambda: ["platform_admin"])
    arguments: Dict[str, Any] = Field(default_factory=dict)
    justification: str = Field(default="Automated S&OP / treasury rebalance execution")


class HITLResolutionRequest(BaseModel):
    ticket_id: str = Field(..., description="HITL interrupt ticket ID")
    reviewer: str = Field(default="sr_ops_approver@enterprise.io", description="Human reviewer identity")
    decision: str = Field(..., pattern="^(APPROVED|REJECTED)$", description="APPROVED or REJECTED")
    notes: str = Field(default="Verified parameters against change-control ticket.")


class SnowflakeSQLValidationRequest(BaseModel):
    sql: str = Field(
        default="SELECT fund_id, nav, aum_cad FROM PORTFOLIO_GOLD.FUNDS WHERE active = 1 LIMIT 25",
        description="SQL statement generated by agent",
    )
    role: str = Field(default="ai_platform_reader", description="Snowflake RBAC role")
    schema_name: str = Field(default="PORTFOLIO_GOLD", description="Target Snowflake schema")


class SnowflakeCortexQueryRequest(BaseModel):
    query: str = Field(
        default="RRSP contribution compliance rules and equity settlement SLA",
        description="Search query for Snowflake Cortex Search",
    )
    role: str = Field(default="ai_platform_reader", description="Snowflake RBAC role")
    top_k: int = Field(default=3, ge=1, le=10)


class IICSTaskflowWebhookPayload(BaseModel):
    taskflow_name: str = Field(default="tf_snowflake_fund_docs_elt")
    status: str = Field(default="SUCCESS")
    rows_processed: int = Field(default=1450)
    freshness_lag_minutes: int = Field(default=8)


class PostgresQueryRequest(BaseModel):
    sql: str = Field(
        default="SELECT account_id, portfolio_name, balance_usd, risk_tier FROM accounts ORDER BY balance_usd DESC",
        description="Parameterized SQL query against PostgreSQL enterprise ledger",
    )
    params: List[Any] = Field(default_factory=list)
    role: str = Field(default="analyst")


class PostgresSnapshotRequest(BaseModel):
    snapshot_name: str = Field(default="pre_agent_mutation_snap_01")


class BedrockStructuredInvokeRequest(BaseModel):
    prompt: str = Field(
        default="Analyze portfolio compliance for Fund POL-101 and output structured risk assessment.",
        description="Prompt sent to Amazon Bedrock Converse API",
    )
    required_keys: List[str] = Field(
        default_factory=lambda: ["summary", "risk_tier", "recommended_action", "confidence_score"]
    )
    simulate_flaky_first_attempt: bool = Field(
        default=True,
        description="Simulate a missing schema key on attempt 1 to demonstrate self-healing retry",
    )


class TelemetrySpanRequest(BaseModel):
    span_name: str = Field(default="mcp.tool.snowflake_cortex_search")
    use_case: str = Field(default="advisor_rag_assistant")
    latency_ms: float = Field(default=142.5)
    status: str = Field(default="OK")
    prompt_tokens: int = Field(default=620)
    completion_tokens: int = Field(default=185)
    error_message: Optional[str] = Field(default=None)


class RunbookLookupRequest(BaseModel):
    incident_type: str = Field(default="iics_taskflow_failed")
    component: str = Field(default="Informatica_Snowflake_ELT")
